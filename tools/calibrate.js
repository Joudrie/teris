// Sets each level's piece budget from play. For every level the human-ish bot plays with
// no budget and we record how many pieces it needed to fill the bar. The budget is the
// number of pieces that the target share of those games managed within, so the share of
// casual players who clear it first time matches the sawtooth in levels.js.
//
//   node tools/calibrate.js --games 40          writes src/budgets.js

import fs from 'node:fs';
import { runParallel } from './rig.js';
import { targetWinRate, levelConfig } from '../src/levels.js';
import { TOTAL_LEVELS } from '../src/core.js';

const a = process.argv.slice(2);
const o = {};
for (let i = 0; i < a.length; i += 2) o[a[i].replace(/^--/, '')] = a[i + 1];
const games = +(o.games || 40);
const from = +(o.from || 1);
const to = +(o.to || TOTAL_LEVELS);

const jobs = [];
for (let level = from; level <= to; level++) {
  const n = level <= 20 ? Math.round(games * 1.5) : games;
  for (let i = 0; i < n; i++) jobs.push({ level, bot: 'human', seed: 900001 + level * 7919 + i * 31 });
}
const t0 = Date.now();
const res = await runParallel(jobs, 'need');
const by = new Map();
for (const r of res) {
  if (!by.has(r.level)) by.set(r.level, []);
  by.get(r.level).push(r.need);
}
const file = 'src/budgets.js';
const old = fs.existsSync(file) ? (await import(`../${file}?t=${Date.now()}`)).BUDGETS : {};
const budgets = { ...old };
const raw = {};
console.log('lvl goal target  need(p25/p50/p75)  topped  budget');
for (const [level, needs] of [...by.entries()].sort((x, y) => x[0] - y[0])) {
  const sorted = needs.sort((x, y) => x - y);
  const target = targetWinRate(level);
  const finite = sorted.filter(Number.isFinite);
  // Needs bunch up on a few values, so a plain percentile can land on a big tie (target
  // 40%, but 65% of players need that number or fewer). Pick the budget whose share of
  // games won is closest to the target instead.
  let b = finite.length ? finite[finite.length - 1] + 2 : levelConfig(level).goal.pieces * 2;
  let bestErr = Infinity;
  for (let cand = finite[0] ?? b; cand <= (finite[finite.length - 1] ?? b); cand++) {
    const share = sorted.filter((n) => n <= cand).length / sorted.length;
    const err = Math.abs(share - target);
    if (err < bestErr - 1e-9) { bestErr = err; b = cand; }
  }
  budgets[level] = b;
  raw[level] = sorted.map((n) => (Number.isFinite(n) ? n : null));
  const q = (p) => sorted[Math.floor(p * (sorted.length - 1))];
  console.log([String(level).padStart(3), String(levelConfig(level).goal.pieces).padStart(4), target.toFixed(2).padStart(6),
    `${q(0.25)}/${q(0.5)}/${q(0.75)}`.padStart(18), String(sorted.length - finite.length).padStart(7), String(b).padStart(7)].join(' '));
}
const body = Object.entries(budgets).sort((x, y) => x[0] - y[0]).map(([l, b]) => `${l}: ${b}`).join(', ');
fs.writeFileSync(file, `// Generated by tools/calibrate.js (${new Date().toISOString().slice(0, 10)}, ${games} human-bot games per level).\n// Piece budget per level: pieces a casual player gets to fill the drain bar.\nexport const BUDGETS = { ${body} };\n`);
fs.mkdirSync('docs/data', { recursive: true });
fs.writeFileSync('docs/data/calibration.json', JSON.stringify(raw));
console.log(`wrote ${file} in ${((Date.now() - t0) / 1000).toFixed(0)} s`);
